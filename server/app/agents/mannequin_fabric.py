"""원단 패턴 2패스 — 미세 반복 패턴(스트라이프·체크)을 상품 사진 기준으로 다시 입힌다.

왜 2패스인가(2026-08-01 관측): 같은 모델·같은 해상도 설정인데 **인물 착용컷(2K)은 줄의 두 색
페어가 살아 나오고, 마네킹컷(4K)은 단색으로 뭉갠다.** 즉 해상도나 모델 성능이 아니다.
두 파이프라인의 차이는 구성이다 — 마네킹은 베이스 마네킹을 캔버스로 주고 "몸·포즈·프레이밍·
배경을 그대로 유지하라"를 강하게 요구하는 편집형이라, 모델의 주의가 베이스 보존에 쏠리고
옷 표면은 부차가 된다. 생성 프롬프트에 패턴 지시를 길게 넣어봐도 개선되지 않았다(오늘 실측:
장문 지시를 넣은 쪽이 한 줄짜리 착용컷보다 못했다).

그래서 과제를 분리한다. 1패스는 지금처럼 몸·핏·구도를 맞추고, 2패스는 **표면 패턴 하나만**
고친다 — 이미지 1장·과제 1개일 때 모델이 반영한다는 것은 가슴 2패스에서 이미 확인된 성질이다.

가슴 2패스의 실패에서 가져온 규율:
  · 압박 문구("최대한", "확신 없으면 더 세게")를 쓰지 않는다 — 측정으로 기각됐고, 옷을 조여
    핏을 깨뜨렸다.
  · 무엇을 지키는지를 명시한다(핏·실루엣·포즈·구도·구성). 회귀는 `edit_regressed` 가 잡는다.
"""

_FINE_PATTERN_ONLY = True  # 무지 상품에는 돌리지 않는다 — 고칠 고주파가 없고 호출만 나간다


def should_apply(mode: str, has_fine_pattern: bool, has_product_images: bool) -> bool:
    """2패스를 돌릴지. 플래그 on + 미세 패턴 상품 + **원단 근거 사진이 있을 때**만.

    상품 사진이 없으면 무엇을 기준으로 고칠지가 없다 — 근거 없이 돌리면 모델이 패턴을
    지어낸다(ADR-0004 정확성 최우선). 무지 상품은 재현할 고주파가 없어 대상이 아니다.
    """
    if mode != "on":
        return False
    if _FINE_PATTERN_ONLY and not has_fine_pattern:
        return False
    return bool(has_product_images)


def build_prompt(template: str) -> str:
    """원단 2패스 템플릿. 치환 토큰이 없다 — 지시가 상품과 무관하게 동일하고,
    패턴의 실제 모습은 첨부된 상품 사진이 말한다(문장으로 옮기면 그 과정에서 왜곡된다)."""
    if "${" in template:
        leftover = sorted({p.split("}")[0] + "}" for p in template.split("${")[1:]})
        raise ValueError(f"원단 프롬프트 템플릿에 해결되지 않은 토큰: {leftover}")
    return template
