"""토스페이먼츠 기관 코드 — 응답의 두 자리 코드를 사람이 읽는 이름으로.

출처: https://docs.tosspayments.com/codes/org-codes (2026-09-10 기준)

**왜 필요한가**: API 버전 2024-06-01 부터 자동결제 응답에서 `cardCompany` 가 제거됐고
`card.issuerCode` 만 온다. 그대로 두면 화면에 '····701*' 처럼 카드사 없이 뜬다.

**코드는 응답 전용이다.** 요청에는 숫자·한글·영문을 다 받지만 응답은 항상 두 자리다.
그래서 이 표는 '두 자리 → 이름' 한 방향만 담는다.

모르는 코드는 None 을 돌려준다 — 추측해서 엉뚱한 카드사를 표시하느니 이름을 비운다.
"""

