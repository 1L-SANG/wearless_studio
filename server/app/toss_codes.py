def card_issuer_name(issuer_code: str | None) -> str | None:
    """두 자리 발급사 코드 → 카드사명. 모르는 코드면 None(이름 없이 표시)."""
    if not issuer_code:
        return None
    return CARD_ISSUERS.get(str(issuer_code).strip().upper())
